    <div class="cp-section-head">
      <p class="cp-section-kicker">Perguntas frequentes</p>
      <h2>FAQ sobre cálculo de rescisão</h2>
      <p>Respostas diretas sobre o escopo desta calculadora, os motivos suportados e as parcelas que ainda não entram na estimativa automática.</p>
    </div>

    <div class="cp-faq-list">
      <details class="cp-faq-item">
        <summary>A calculadora mostra o total da minha rescisão?</summary>
        <div class="cp-faq__body"><p>Não. O resultado é deliberadamente parcial. A ferramenta separa o que consegue calcular do que permanece fora do modelo automático, evitando apresentar um total incompleto como se fosse o valor final do TRCT.</p></div>
      </details>

      <details class="cp-faq-item">
        <summary>A calculadora funciona para pedido de demissão?</summary>
        <div class="cp-faq__body"><p>Sim. Pedido de demissão é uma das quatro modalidades atualmente suportadas. A estimativa continua limitada às parcelas explicitamente cobertas pelo H29.</p></div>
      </details>

      <details class="cp-faq-item">
        <summary>Posso calcular demissão sem justa causa?</summary>
        <div class="cp-faq__body"><p>Sim. A demissão sem justa causa está entre os motivos suportados e pode incluir saldo de salário, 13º proporcional e férias proporcionais dentro do escopo atual.</p></div>
      </details>

      <details class="cp-faq-item">
        <summary>A rescisão por acordo do art. 484-A é suportada?</summary>
        <div class="cp-faq__body"><p>Sim. O acordo do art. 484-A está na matriz suportada. A ferramenta não transforma, porém, todas as consequências possíveis desse desligamento em um total de rescisão.</p></div>
      </details>

      <details class="cp-faq-item">
        <summary>FGTS, multa de 40% e aviso prévio entram?</summary>
        <div class="cp-faq__body"><p>Não nesta versão. Multa e saque do FGTS, aviso prévio ou desconto de aviso e outras parcelas permanecem explicitamente fora do cálculo automático.</p></div>
      </details>

      <details class="cp-faq-item">
        <summary>Por que férias podem ter mais avos que o 13º?</summary>
        <div class="cp-faq__body"><p>Porque são contagens diferentes. O 13º usa o ano civil; as férias proporcionais usam o período aquisitivo iniciado na data de admissão.</p></div>
      </details>

      <details class="cp-faq-item">
        <summary>A calculadora monetiza férias vencidas ou em dobro?</summary>
        <div class="cp-faq__body"><p>Não. A ferramenta pode sinalizar férias adquiridas ou vencidas, mas não converte automaticamente essa sinalização em valor nem presume eventual dobra sem regra específica.</p></div>
      </details>
    </div>
