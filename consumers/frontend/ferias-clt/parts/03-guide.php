  <div class="cp-center">
    <div class="cp-section-head">
      <p class="cp-section-kicker">Como a ferramenta trabalha</p>
      <h2>O que esta calculadora de férias separa</h2>
      <p>Férias não são uma única linha. Para o cálculo ficar auditável, a ferramenta mantém separados o direito adquirido em dias, os dias de gozo, o abono pecuniário, o terço constitucional e os descontos incidentes sobre cada componente.</p>
    </div>

    <div class="vf-guide-grid">
      <article class="cp-card vf-guide-card">
        <h3>Faltas definem primeiro o direito</h3>
        <p>A entrada de faltas injustificadas é comparada com as faixas declaradas pela release fiscal. O resultado pode ser 30, 24, 18 ou 12 dias dentro do escopo automatizado. A ferramenta não usa uma escolha arbitrária de “quantos dias tirar” como se isso definisse o direito adquirido.</p>
      </article>

      <article class="cp-card vf-guide-card" id="abono-pecuniario">
        <h3>Abono pecuniário: vender 1/3 das férias</h3>
        <p>Ao marcar a venda, os dias convertidos são calculados sobre o período a que o empregado efetivamente tem direito. Assim, 30 dias geram 10 dias de abono e 20 de gozo; 24 geram 8 e 16; 18 geram 6 e 12; 12 geram 4 e 8.</p>
      </article>

      <article class="cp-card vf-guide-card">
        <h3>Principal e 1/3 constitucional ficam visíveis</h3>
        <p>A base informada representa o principal integral das férias para o período adquirido, antes do adicional constitucional. Se houver abono, a ferramenta separa a fração correspondente do principal e calcula o respectivo terço como componente próprio.</p>
      </article>

      <article class="cp-card vf-guide-card">
        <h3>INSS e IRRF seguem incidências diferentes</h3>
        <p>Férias gozadas e o terço correspondente entram na base previdenciária. O principal do abono e o terço sobre o abono são tratados separadamente conforme os perfis fiscais declarados pela release. O IRRF de férias permanece uma apuração própria.</p>
      </article>
    </div>
  </div>
</section>

<section class="padding-gerais py-xy">
  <div class="cp-center cp-grid">
    <article class="cp-card">
      <h2 class="mb-md">Como usar a base de férias</h2>
      <p>Informe o valor principal que corresponde ao período integral de férias adquirido, antes do adicional de 1/3. Para um empregado com direito a 30 dias e remuneração fixa sem componentes adicionais, esse valor normalmente coincide com a remuneração-base de férias.</p>
      <p>Quando houver médias, adicionais ou redução do período por faltas, use a base já apurada pela folha. A calculadora não reconstrói médias de horas extras, comissão ou adicional noturno.</p>
    </article>

    <article class="cp-card">
      <h2 class="mb-md">Por que o líquido não é apenas “salário + 1/3”</h2>
      <p>O total bruto pode conter componentes com incidências diferentes. Além disso, o IRRF considera deduções próprias da apuração de férias e compara as deduções legais com o desconto simplificado previsto na release.</p>
      <p>Por isso, a memória mostra separadamente base previdenciária, INSS, rendimento tributável, base do IRRF, redução aplicada e IRRF final.</p>
    </article>
  </div>
</section>

