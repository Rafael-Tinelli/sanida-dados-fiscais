        <h2>Como entender o cálculo do décimo terceiro salário</h2>
        <p>
          O valor do 13º depende da remuneração considerada, da quantidade de avos e do que já foi antecipado.
          A memória da calculadora separa essas etapas para que você consiga conferir a conta sem misturar 1ª parcela, quitação e descontos.
        </p>
