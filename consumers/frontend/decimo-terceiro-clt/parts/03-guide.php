      <article class="cp-card cp-card--reading">
        <h2>Como calcular o décimo terceiro salário</h2>
        <p>
          A base do cálculo é dividida em <strong>12 avos</strong>. Cada mês que cumpre a regra de contagem acrescenta 1/12 ao direito anual.
          Com 12/12, o 13º bruto tende a corresponder à remuneração de referência integral; com menos avos, o valor é proporcional.
        </p>
        <p>
          Nesta ferramenta, a base reúne a remuneração fixa informada e, quando existir, uma <strong>média monetária de variáveis já apurada</strong>.
          A calculadora não transforma horas, percentuais ou produção em média: ela recebe esse valor pronto para não inventar uma regra que depende da folha real.
        </p>

        <h2 id="decimo-terceiro-proporcional">Décimo terceiro proporcional e regra dos 15 dias</h2>
        <p>
          O 13º proporcional é calculado em avos. Quando você escolhe a contagem por datas, o motor verifica mês a mês o período trabalhado no ano de referência e aplica o limiar contratual de <strong>15 dias</strong>.
        </p>
        <p>
          Por isso, alguém que trabalhou sete meses não deve simplesmente multiplicar o salário por 7/12 sem antes verificar se cada mês realmente qualificou para a contagem. A ferramenta permite informar os avos diretamente quando essa apuração já estiver conhecida ou calculá-los pelas datas do vínculo.
        </p>

        <h2 id="primeira-parcela-decimo-terceiro">Como funciona a primeira parcela do décimo terceiro</h2>
        <p>
          A 1ª parcela é um <strong>adiantamento</strong>. No ramo padrão coberto pela ferramenta, ela usa como referência metade do salário recebido no mês anterior ao pagamento, dentro da janela prevista pelo contrato fiscal — não metade do 13º total recalculado depois.
        </p>
        <p>
          Há situações em que a ferramenta não presume esse valor. Se houve admissão no ano ou remuneração variável que exija tratamento específico, o caminho seguro é informar a <strong>1ª parcela efetivamente paga</strong>. Isso evita reconstruir retrospectivamente um adiantamento com dados insuficientes.
        </p>

        <h2 id="segunda-parcela-decimo-terceiro">Como funciona a segunda parcela do décimo terceiro</h2>
        <p>
          A 2ª parcela não é simplesmente “a outra metade”. A quitação parte do 13º total, desconta o adiantamento e, quando a estimativa líquida está ativa, considera também a apuração separada de INSS e IRRF do 13º.
        </p>
        <p>
          É possível, portanto, que o saldo líquido fique zerado. Se adiantamento e descontos superarem o saldo disponível, a calculadora <strong>não mostra uma parcela negativa a pagar</strong>: ela mantém o valor pagável em R$ 0,00 e apresenta a insuficiência separadamente para conferência.
        </p>

        <h2>INSS e IRRF do décimo terceiro</h2>
        <p>
          O 13º possui avaliações próprias de INSS e IRRF, separadas da folha mensal comum. A ferramenta mostra a contribuição previdenciária, a base de IRRF, o imposto antes de eventual redutor, o modo de dedução e a redução aplicada quando houver.
        </p>
        <p>
          Isso ajuda a explicar por que a 2ª parcela líquida pode ser significativamente menor do que a 1ª parcela, mesmo quando o 13º bruto anual parece próximo de uma remuneração mensal.
        </p>

        <h2>Comissão, horas extras e adicionais entram no 13º?</h2>
        <p>
          Verbas variáveis podem influenciar a remuneração considerada para o décimo terceiro. O ponto importante é que a média precisa estar <strong>apurada antes</strong> de chegar à calculadora.
        </p>
        <p>
          Se você recebe comissão, horas extras, adicional noturno ou outra verba variável habitual, informe no campo de média apenas o valor monetário já obtido pela apuração competente. Esta ferramenta não calcula quantidades de horas, percentuais, DSR ou critérios de média específicos do vínculo.
        </p>

        <h2>Como conferir o resultado</h2>
        <p>
          Comece pelos três números principais: <strong>13º total, 1ª parcela e 2ª parcela a pagar</strong>. Depois abra a composição para verificar avos, descontos e eventual insuficiência. Os detalhes fiscais ficam em uma camada separada, com a data de referência e a release utilizada.
        </p>
        <p>
          A simulação é uma ferramenta de conferência. Folha de pagamento, recibos e informações reais do vínculo continuam sendo as referências para validar médias, adiantamentos e situações não representadas pelos campos disponíveis.
        </p>
